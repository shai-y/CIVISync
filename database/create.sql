CREATE DATABASE IF NOT EXISTS lgu_assist_oop CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE lgu_assist_oop;
CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, full_name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 mobile VARCHAR(11) NOT NULL UNIQUE, barangay VARCHAR(100) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(12) NOT NULL DEFAULT 'RESIDENT', enabled BOOLEAN NOT NULL DEFAULT TRUE,
 joined TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS teams (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE,
 category VARCHAR(100) NOT NULL, leader VARCHAR(120) NOT NULL, members INT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS requests (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT NOT NULL, submission CHAR(36) NOT NULL,
 category VARCHAR(60) NOT NULL, location VARCHAR(200) NOT NULL, details VARCHAR(1200) NOT NULL,
 priority VARCHAR(12) NOT NULL DEFAULT 'Medium', status VARCHAR(24) NOT NULL DEFAULT 'Pending',
 team_id BIGINT UNIQUE, note VARCHAR(500) NOT NULL DEFAULT '', revision INT NOT NULL DEFAULT 0,
 filed TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, responded DATETIME, resolved DATETIME,
 UNIQUE(owner_id,submission), FOREIGN KEY(owner_id) REFERENCES accounts(id), FOREIGN KEY(team_id) REFERENCES teams(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notices (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, author_id BIGINT NOT NULL, title VARCHAR(150) NOT NULL,
 category VARCHAR(30) NOT NULL, message VARCHAR(2000) NOT NULL, posted TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(author_id) REFERENCES accounts(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS activity (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT NOT NULL, action VARCHAR(100) NOT NULL,
 record_label VARCHAR(160) NOT NULL, logged TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_id) REFERENCES accounts(id)
) ENGINE=InnoDB;
